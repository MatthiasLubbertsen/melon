export type Lang = 'nl' | 'en'
export type Key = keyof typeof nl
const dicts = { nl, en }

type I18n = {
  lang: Lang
  locale: string
  setLang: (l: Lang) => void
  t: (key: Key, vars?: Record<string, string | number>) => string
  /** Picks the _one/_other variant for a count. */
  plural: (base: string, n: number) => string
  /** A readable message for an API error code. */
  error: (e: unknown) => string
}

const Ctx = createContext<I18n | null>(null)

function initialLang(): Lang {
  try {
    return localStorage.getItem('melon.lang') === 'en' ? 'en' : 'nl'
  } catch {
    return 'nl'
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])
  const setLang = useCallback((l: Lang) => {
    setLangState(l)
    try {
      localStorage.setItem('melon.lang', l)
    } catch {
      /* private mode */
    }
  }, [])
  const value = useMemo<I18n>(() => {
    const dict = dicts[lang]
    const t: I18n['t'] = (key, vars) => {
      let s: string = dict[key] ?? key
      if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v))
      return s
    }
    return {
      lang,
      locale: lang === 'nl' ? 'nl-NL' : 'en-GB',
      setLang,
      t,
      plural: (base, n) => t(`${base}_${n === 1 ? 'one' : 'other'}` as Key, { n }),
      error: (e) => {
        const code = (e as { code?: string })?.code
        const key = `err_${code}` as Key
        return key in dict ? t(key) : t('err_generic')
      },
    }
  }, [lang, setLang])
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>
}

export function useI18n(): I18n {
  const v = useContext(Ctx)
  if (!v) throw new Error('useI18n outside provider')
  return v
}
